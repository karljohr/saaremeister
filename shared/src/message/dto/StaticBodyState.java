package message.dto;

public class StaticBodyState {
    public float x, y;
    public float width;
    public float height;

    public StaticBodyState() {}

    public StaticBodyState(float x, float y, float width, float height) {
        this.x = x;
        this.y = y;
        this.width = width;
        this.height = height;
    }
}
